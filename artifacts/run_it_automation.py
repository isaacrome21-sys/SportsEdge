def build_run_it_plan(command_text: str) -> dict:
    """Build the execution plan for a "run it" command.

    Returns a dict with:
    - parsed command
    - browser prompts for DK, OddsPortal, Action Network
    - instructions for the parent agent

    The parent agent executes the browser tasks and feeds results back
    into `execute_run_it_plan()`.
    """
    cmd = parse_run_it_command(command_text)

    return {
        "command": {
            "raw": cmd.raw,
            "sport": cmd.sport,
            "teams": cmd.teams,
            "scope": cmd.scope_description,
        },
        "browser_tasks": {
            "draftkings": {
                "prompt": build_dk_browser_prompt(cmd),
                "purpose": "Current odds/lines for pricing",
            },
            "oddsportal": {
                "prompt": build_oddsportal_prompt(cmd),
                "purpose": "Cross-book comparison and line movement",
                "requires": "Secure Vault credentials",
            },
            "action_network": {
                "prompt": build_action_prompt(cmd),
                "purpose": "Public splits (context only, not pricing)",
                "requires": "Secure Vault credentials",
            },
        },
        "next_step": (
            "Execute the browser tasks, then call execute_run_it_plan() "
            "with the results."
        ),
    }


def execute_run_it_plan(plan: dict, dk_text: str,
                        oddsportal_data: dict = None,
                        action_data: dict = None,
                        lane: str = "A",
                        min_ev: float = 0.02) -> str:
    """Execute the model run and generate the card.

    Args:
        plan: Plan from build_run_it_plan()
        dk_text: Raw browser output from DK line pull
        oddsportal_data: Parsed OddsPortal data (optional)
        action_data: Parsed Action Network data (optional)
        lane: Pricing lane ("A" for independent, "B" for anchored)
        min_ev: Minimum EV threshold

    Returns:
        Formatted uniform research card (string)
    """
    cmd_info = plan["command"]
    sport = cmd_info.get("sport")
    if not sport:
        # A board pull is for one sport's board; without a resolved
        # sport the intake cannot label rows truthfully. Fail closed
        # instead of defaulting to a sport the board may not be.
        raise ValueError("INTAKE_SPORT_UNRESOLVED")
    now = datetime.now(timezone.utc)

    # Parse DK lines
    lines = parse_extended_browser_lines(dk_text, sport=sport, now=now)
    if not lines:
        return (
            "No lines parsed from DK output.\n"
            "Check that the browser returned lines in the expected format."
        )

    # Run through the model
    card = run_model(lines, sport=sport, now=now, lane=lane, min_ev=min_ev)

    # Format the uniform card
    return format_uniform_card(
        card,
        dk_lines=lines,
        oddsportal_data=oddsportal_data,
        action_data=action_data,
    )


