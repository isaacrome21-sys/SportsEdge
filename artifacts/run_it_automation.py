def main(argv=None):
    import argparse
    p = argparse.ArgumentParser(description="Automated 'run it' flow")
    p.add_argument("command", help="'run it' command (e.g., 'run it NFL')")
    p.add_argument("--dk-text", type=str, default=None,
                   help="Path to file with DK browser output (skips browser)")
    p.add_argument("--lane", default="A", choices=["A", "B"])
    p.add_argument("--min-ev", type=float, default=0.02)
    p.add_argument("--plan-only", action="store_true",
                   help="Only output the execution plan (browser prompts)")
    args = p.parse_args(argv)

    plan = build_run_it_plan(args.command)

    if args.plan_only:
        print(json.dumps(plan, indent=2))
        return

    if not args.dk_text:
        print("Browser prompts for parent agent:")
        print()
        print("=== DRAFTKINGS ===")
        print(plan["browser_tasks"]["draftkings"]["prompt"])
        print()
        print("=== ODDSPORTAL ===")
        print(plan["browser_tasks"]["oddsportal"]["prompt"])
        print()
        print("=== ACTION NETWORK ===")
        print(plan["browser_tasks"]["action_network"]["prompt"])
        print()
        print("Run with --dk-text <file> after collecting browser output.")
        return

    with open(args.dk_text) as f:
        dk_text = f.read()

    card_text = execute_run_it_plan(
        plan, dk_text, lane=args.lane, min_ev=args.min_ev)
    print(card_text)


if __name__ == "__main__":
    main()
