# 3. Line parsing (extends run_it_browser.py)
#
# Intake contract (Oct 13, 2026 defect fix): the sport comes from the
# board/context and is REQUIRED -- there is no default sport anywhere
# in this layer. Prop rows carry the away/home of the game they were
# parsed under; a prop with no game context is refused with a named
# reason instead of floating unbound. Kickoffs are normalized by the
# base parser's strict datetime parser (documented formats only).
# The board's declared source (its SOURCE header, or the caller's
# board_book) is stamped on prop/team-prop rows as `book`, exactly as
# the base parser stamps game rows; an undeclared board stamps
# nothing. TEAM_PROP additionally documents two single-price shapes
# (SPREAD_1H with a line, ML_1H without) beside the O/U pair shape.
# ---------------------------------------------------------------------------

def parse_prop_line(line: str, current_game: dict, sport: str, now: datetime,
                    book: str = None) -> Optional[dict]:
    """Parse a PROP: line into a run_full input object."""
    # PROP: <Player> (<Team>) | <Market> | <Line> | O (<odds>) | U (<odds>)
    m = re.match(
        r'PROP:\s*(.+?)\s*\((.+?)\)\s*\|\s*(.+?)\s*\|\s*([\d.]+)\s*\|\s*O\s*\(([+-]?\d+)\)\s*\|\s*U\s*\(([+-]?\d+)\)',
        line)
    if not m:
        return None
    if not current_game.get('away') or not current_game.get('home'):
        # A prop row that cannot be tied to its game's away/home sides
        # is rejected, never floated unbound.
        raise ValueError(f"INTAKE_PROP_UNBOUND_NO_GAME_CONTEXT:{line}")
    player, team, market, line_val, over_odds, under_odds = m.groups()
    market = market.strip().upper().replace(' ', '_')
    base = {
        'sport': sport,
        'away': current_game['away'],
        'home': current_game['home'],
        'player': player.strip(),
        'team': team.strip(),
        'market': market,
        'line': float(line_val),
        'kickoff': current_game.get('kickoff', ''),
        'quote_captured_at': now.isoformat(),
    }
    if book:
        base['book'] = book
    # Return two rows: over and under
    over_row = dict(base, side='OVER', odds=int(over_odds))
    under_row = dict(base, side='UNDER', odds=int(under_odds))
    return [over_row, under_row]


def parse_team_prop_line(line: str, current_game: dict, sport: str,
                         now: datetime, book: str = None) -> Optional[list]:
    """Parse a TEAM_PROP: line into run_full input objects.

    Documented shapes:
    - O/U pair:  TEAM_PROP: <Team> | <Market> | <Line> | O (<odds>) |
      U (<odds>)  ->  the OVER / UNDER row pair (bare sides), with the
      team identity carried by `team` plus a strictly resolved
      `team_side` (see _resolve_team_side).
    - Single-price spread:  TEAM_PROP: <Team> | SPREAD_1H | <Line> |
      <odds>  ->  one row, side AWAY/HOME (the side convention
      run_it_full's phone rows use for SPREAD_1H).
    - Single-price moneyline:  TEAM_PROP: <Team> | ML_1H | <odds>
      ->  one row, side AWAY/HOME, no line.

    The single-price shapes exist because a first-half spread or
    moneyline quote names ONE team's price; the opposing team's own
    TEAM_PROP line carries its price. There is no second price to
    pair with, so nothing is synthesized. Any other single-price
    market is not a documented shape and returns None, as before.
    A matched shape with no game context is refused with
    INTAKE_TEAM_PROP_UNBOUND_NO_GAME_CONTEXT, never floated unbound.
    """
    # TEAM_PROP: <Team> | <Market> | <Line> | O (<odds>) | U (<odds>)
    m = re.match(
        r'TEAM_PROP:\s*(.+?)\s*\|\s*(.+?)\s*\|\s*([\d.]+)\s*\|\s*O\s*\(([+-]?\d+)\)\s*\|\s*U\s*\(([+-]?\d+)\)',
        line)
    if m:
        if not current_game.get('away') or not current_game.get('home'):
            raise ValueError(
                f"INTAKE_TEAM_PROP_UNBOUND_NO_GAME_CONTEXT:{line}")
        team, market, line_val, over_odds, under_odds = m.groups()
        market = market.strip().upper().replace(' ', '_')
        # Emit the canonical row shape the pricing consumers require:
        # a bare OVER/UNDER side, with team identity carried by the
        # team field plus a strictly resolved team_side. The pre-fix
        # compound side ("AWAY_OVER") was refused by
        # free_models.calculate() with
        # TEAM_TOTALS_TEAM_OR_SIDE_UNVERIFIED and by team_half_pricing's
        # side check; only the F5 phone pricer tolerated it. An
        # unresolvable team gets NO team_side (never a defaulted AWAY):
        # the row keeps its verbatim team string and downstream
        # verification fails closed.
        base = {
            'sport': sport,
            'away': current_game.get('away', ''),
            'home': current_game.get('home', ''),
            'team': team.strip(),
            'market': market,
            'line': float(line_val),
            'kickoff': current_game.get('kickoff', ''),
            'quote_captured_at': now.isoformat(),
        }
        if book:
            base['book'] = book
        team_side = _resolve_team_side(team, current_game)
        if team_side is not None:
            base['team_side'] = team_side
        over_row = dict(base, side='OVER', odds=int(over_odds))
        under_row = dict(base, side='UNDER', odds=int(under_odds))
        return [over_row, under_row]

    # Single-price shapes: a signed line + one price (spread), or one
    # price alone (moneyline). The market decides which; anything else
    # is not a documented shape.
    m = re.match(
        r'TEAM_PROP:\s*(.+?)\s*\|\s*(.+?)\s*\|\s*([+-]?\d+\.?\d*)\s*\|\s*([+-]?\d+)\s*$',
        line)
    line_val = None
    if m:
        team, market, line_val, odds = m.groups()
    else:
        m = re.match(
            r'TEAM_PROP:\s*(.+?)\s*\|\s*(.+?)\s*\|\s*([+-]?\d+)\s*$',
            line)
        if not m:
            return None
        team, market, odds = m.groups()
    market = market.strip().upper().replace(' ', '_')
    if line_val is not None and market != 'SPREAD_1H':
        return None
    if line_val is None and market != 'ML_1H':
        return None
    if not current_game.get('away') or not current_game.get('home'):
        raise ValueError(
            f"INTAKE_TEAM_PROP_UNBOUND_NO_GAME_CONTEXT:{line}")
    # Determine home/away for team (same rule as the O/U pair shape)
    side = 'HOME' if team.strip().lower() in current_game.get('home', '').lower() else 'AWAY'
    row = {
        'sport': sport,
        'away': current_game.get('away', ''),
        'home': current_game.get('home', ''),
        'team': team.strip(),
        'market': market,
        'kickoff': current_game.get('kickoff', ''),
        'quote_captured_at': now.isoformat(),
        'side': side,
        'odds': int(odds),
    }
    if line_val is not None:
        row['line'] = float(line_val)
    if book:
        row['book'] = book
    return [row]


def _resolve_team_side(team_name, current_game):
    """Resolve a TEAM_PROP team token to 'HOME'/'AWAY' by strict identity.

    Exact normalized match first; a unique containment match second
    (boards have abbreviated, e.g. "Rays" for "Tampa Bay Rays").
    Anything else -- a team outside the fixture, an ambiguous token,
    or a non-team token such as "Game" on a game-level market --
    resolves to None so no identity is ever guessed.
    """
    def _norm(value):
        return ' '.join(str(value or '').split()).casefold()

    token = _norm(team_name)
    if not token:
        return None
    home = _norm(current_game.get('home'))
    away = _norm(current_game.get('away'))
    if token == home:
        return 'HOME'
    if token == away:
        return 'AWAY'
    hits = [side for side, full in (('HOME', home), ('AWAY', away))
            if full and (token in full or full in token)]
    return hits[0] if len(hits) == 1 else None


def _normalize_kickoff(kickoff_str: str, *, reference_now=None,
                       board_tz=None) -> str:
    """Normalize a kickoff string to ISO-8601 UTC.

    Compatibility wrapper over the base parser's strict parser
    (run_it_browser.parse_kickoff_datetime): documented formats only;
    anything else raises a named INTAKE_KICKOFF_* refusal instead of
    being passed through raw for a downstream stage to guess at.
    """
    from run_it_browser import parse_kickoff_datetime
    if reference_now is None:
        reference_now = datetime.now(timezone.utc)
    return parse_kickoff_datetime(
        kickoff_str, reference_now=reference_now, board_tz=board_tz)


def parse_extended_browser_lines(text: str, sport: str, now=None,
                                 board_tz=None, board_book=None) -> list:
    """Parse extended browser output (game lines + props + team props).

    Extends the basic parser in run_it_browser.py with PROP: and
    TEAM_PROP: lines. `sport` is REQUIRED: it is the sport of the
    board being parsed, taken from the caller's context. Aliases
    (e.g. "baseball") are canonicalized; anything unrecognized is
    refused by the base parser (INTAKE_SPORT_UNRECOGNIZED) and a
    missing sport is refused here (INTAKE_SPORT_REQUIRED).

    `board_book` resolves exactly as in the base parser: the explicit
    argument wins, else the capture's own SOURCE header declaration;
    the resolved value is stamped on every row as `book`, and an
    undeclared board stamps nothing.
    """
    from run_it_browser import (
        board_source_from_header, board_zone_from_quote_time,
        parse_browser_lines, parse_game_header, validate_sport)

    if now is None:
        now = datetime.now(timezone.utc)
    if sport is None or not str(sport).strip():
        raise ValueError("INTAKE_SPORT_REQUIRED")
    canonical = SPORT_ALIASES.get(str(sport).strip().upper(),
                                  str(sport).strip().upper())
    canonical = validate_sport(canonical)
    if board_tz is None:
        board_tz = board_zone_from_quote_time(text)
    if board_book is None:
        board_book = board_source_from_header(text)

    lines = parse_browser_lines(text, sport=canonical, now=now,
                                board_tz=board_tz, board_book=board_book)

    current_game = {}
    for raw_line in text.split('\n'):
        line = raw_line.strip()
        if not line:
            continue
        # Track current game for prop context (same strict header
        # parse the base parser applied; kickoff already normalized).
        header = parse_game_header(line, reference_now=now,
                                   board_tz=board_tz)
        if header is not None:
            current_game = header
            continue
        if line.startswith('PROP:'):
            rows = parse_prop_line(line, current_game, canonical, now,
                                   book=board_book)
            if rows:
                lines.extend(rows)
        elif line.startswith('TEAM_PROP:'):
            rows = parse_team_prop_line(line, current_game, canonical, now,
                                        book=board_book)
            if rows:
                lines.extend(rows)

    # Kickoffs arrive normalized from the parsers above (base game
    # rows from parse_browser_lines, prop rows from the strict header
    # parse); no raw datetime string is passed through for a
    # downstream stage to guess at.
    return lines


