#!/usr/bin/env python3
"""Automated "run it" flow for SportsEdge.

Workflow (per Isaac):
1. Isaac says "run it" (optionally: "run it NFL", "run it Bills/Rams", "run it MLB")
2. System pulls:
   - DraftKings (via browser) — current odds/lines
   - OddsPortal (credentials in Secure Vault) — cross-book comparison, line movement
   - Action Network (credentials in Secure Vault) — public splits, sharp money
   - SportsEdge model — projections
3. System generates and sends the final research card.

Card format (uniform across all sports/markets):
- Play / Line / Price (from DK)
- Model probability
- Fair odds
- No-vig comparison
- Estimated EV%
- Uncertainty bands
- Factor-coverage audit (verified-used vs missing)
- Frozen status badge
- Exact blockers (if any)

Constraints:
- Research-only: never place bets, never modify accounts
- Missing critical factor = blocked with reason, never silently priced
- Untested heuristics (injury/QB, weather) labeled as such on cards
- The 11 earlier signals remain UNVALIDATED — never presented as edges
- Factor audit shows verified-used vs missing for every card

Note on browser access:
This module builds everything except the live browser interaction.
The parent agent (which has live browser access) executes the browser
tasks using the prompts generated by `build_dk_browser_prompt()`.
"""

