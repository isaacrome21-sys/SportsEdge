# Labels for untested heuristics that affect live pricing
UNTESTED_HEURISTIC_LABEL = "UNTESTED_HEURISTIC_ACTIVE_IN_PRICING"

# The 11 earlier signals remain unvalidated
UNVALIDATED_SIGNAL_LABEL = "RESEARCH_SIGNAL_UNVALIDATED"


def _american_to_prob(odds: int) -> float:
    """Convert American odds to implied probability."""
    if odds > 0:
        return 100 / (odds + 100)
    return -odds / (-odds + 100)


def _prob_to_american(p: float) -> str:
    """Convert probability to American odds string."""
    if p <= 0 or p >= 1:
        return "N/A"
    if p >= 0.5:
        return f"{-round(100 * p / (1 - p))}"
    return f"+{round(100 * (1 - p) / p)}"


def format_uniform_card(card: dict, dk_lines: list = None,
                        oddsportal_data: dict = None,
                        action_data: dict = None) -> str:
    """Format a research card into the uniform human-readable card.

    Includes:
    - Play / Line / Price (from DK)
    - Model probability
    - Fair odds
    - No-vig comparison
    - Estimated EV%
    - Uncertainty bands (if available)
    - Factor-coverage audit (verified-used vs missing)
    - Frozen status badge
    - Exact blockers
    - Cross-book comparison (OddsPortal)
    - Public splits (Action Network, context only)
    """
    out = []
    out.append("=" * 60)
    out.append("SPORTSEDGE RESEARCH CARD")
    out.append("=" * 60)
    out.append(f"Generated: {card.get('as_of_utc', 'unknown')}")
    out.append(f"Schema: {card.get('schema', 'unknown')}")
    out.append(f"Research only: {card.get('research_only', True)}")
    out.append("")

    # Frozen status
    frozen = card.get('frozen', False)
    out.append(f"Status: {'🧊 FROZEN' if frozen else 'LIVE'}")
    out.append("")

    rows = card.get('evaluated_rows', [])

    # Group by game (use 'game' field from evaluated rows)
    games = {}
    for r in rows:
        game_key = r.get('game', '? @ ?')
        games.setdefault(game_key, []).append(r)

    for game_key, game_rows in games.items():
        out.append(f"--- {game_key} ---")
        for r in game_rows:
            out.append(format_row(r))
        out.append("")

    # Cross-book comparison (OddsPortal)
    if oddsportal_data:
        out.append("--- CROSS-BOOK (OddsPortal) ---")
        for entry in oddsportal_data.get('comparisons', []):
            out.append(f"  {entry}")
        out.append("")
        if oddsportal_data.get('movements'):
            out.append("Line movement:")
            for m in oddsportal_data['movements']:
                out.append(f"  {m}")
            out.append("")

    # Public splits (Action Network) — context only
    if action_data:
        out.append("--- PUBLIC SPLITS (Action Network — context only) ---")
        for s in action_data.get('splits', []):
            out.append(f"  {s}")
        out.append("")

    # Factor coverage audit
    coverage = card.get('factor_coverage', {})
    if coverage:
        out.append("--- FACTOR COVERAGE AUDIT ---")
        counts = coverage.get('status_counts', {})
        for status, count in sorted(counts.items()):
            out.append(f"  {status}: {count}")
        out.append("")

    # Untested heuristics warning
    out.append("--- VALIDATION STATUS ---")
    out.append(f"  Injury/QB adjustments: {UNTESTED_HEURISTIC_LABEL}")
    out.append("    (active in #2064 pricing, not validated on historical data)")
    out.append(f"  Weather adjustments: {UNTESTED_HEURISTIC_LABEL}")
    out.append("    (active in #2064 pricing, not validated on historical data)")
    out.append(f"  11 earlier signals: {UNVALIDATED_SIGNAL_LABEL}")
    out.append("")

    # Summary
    summary = card.get('summary', {})
    out.append("--- SUMMARY ---")
    out.append(f"  Rows evaluated: {summary.get('rows', 0)}")
    for status, count in sorted(summary.get('status_counts', {}).items()):
        out.append(f"  {status}: {count}")

    out.append("")
    out.append("=" * 60)
    out.append("Research only. Not betting advice. No validated edges claimed.")
    out.append("=" * 60)

    return "\n".join(out)


def format_row(r: dict) -> str:
    """Format a single evaluated row."""
    market = r.get('market', '?')
    # Side may be in 'side' or embedded in 'selection'
    side = r.get('side') or ''
    selection = r.get('selection', '')
    if not side and selection:
        # Extract side from selection like "Buffalo Bills +3.5"
        side = selection
    line = r.get('line')
    line_str = f" {line}" if line is not None else ""
    status = r.get('status', 'UNKNOWN')

    # Get pricing from the independent lane view
    lanes = r.get('pricing_lanes', {})
    lane_a = lanes.get('lane_a_independent', r)  # fallback to row itself

    # DK price
    odds = r.get('odds')
    price_str = f" ({odds:+d})" if odds is not None else ""

    # Model probability
    model_p = lane_a.get('estimate_p')
    model_str = f"{model_p:.1%}" if model_p is not None else "N/A"

    # Fair odds
    fair = lane_a.get('fair_american')
    fair_str = f"{fair:+d}" if fair is not None else "N/A"

    # No-vig comparison
    no_vig = r.get('market_no_vig_p')
    no_vig_str = f"{no_vig:.1%}" if no_vig is not None else "N/A"

    # EV
    ev = lane_a.get('ev_per_dollar')
    ev_str = f"{ev:+.1%}" if ev is not None else "N/A"

    # Uncertainty (if available)
    unc = r.get('uncertainty', {})
    unc_str = ""
    if unc:
        lo = unc.get('ci_lower')
        hi = unc.get('ci_upper')
        if lo is not None and hi is not None:
            unc_str = f" | 95% CI: [{lo:.1%}, {hi:.1%}]"

    # Blockers
    blocker_str = ""
    if 'BLOCKED' in status:
        blocker_str = f" | BLOCKER: {r.get('block_reason', status)}"

    # Untested heuristic flag
    heuristic_str = ""
    pp_adj = r.get('prepricing_adjustments', {})
    adjustments = pp_adj.get('adjustments', {}) if isinstance(pp_adj, dict) else {}
    if adjustments.get('home_injury_pts') or adjustments.get('away_injury_pts'):
        heuristic_str += " [injury/QB: UNTESTED]"
    if adjustments.get('weather_total_adj'):
        heuristic_str += " [weather: UNTESTED]"

    return (
        f"  {market} {side}{line_str}{price_str}\n"
        f"    Model: {model_str} | Fair: {fair_str} | "
        f"No-vig: {no_vig_str} | EV: {ev_str}{unc_str}\n"
        f"    Status: {status}{blocker_str}{heuristic_str}"
    )


